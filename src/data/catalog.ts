const I: Level = 'intermedio';
const A: Level = 'avanzado';

const t = (
  id: string,
  name: string,
  category: Category,
  level: Level,
  from: Ref,
  to: Ref | null,
  description: string,
): Technique => ({ id, name, category, level, from: ref(from), to: to ? ref(to) : undefined, description });

